const fs = require('node:fs/promises'),
  path = require('node:path'),
  crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  let out = [];
  for (const e of entries) {
    const p = path.join(dir, e.name);
    out.push(...(e.isDirectory() ? await walk(p) : [p]));
  }
  return out;
}
(async () => {
  const paths = ['index.html'];
  for (const dir of ['web', 'pdf-parser', 'cloud'])
    for (const file of await walk(path.join(root, dir))) {
      const rel = path.relative(root, file).split(path.sep).join('/');
      if (rel === 'web/icons/source-wallet.png') continue;
      if (/\.(?:html|mjs|js|css|webmanifest|png|bcmap|pfb|ttf|otf|woff2?)$/.test(rel)) paths.push(rel);
    }
  paths.sort();
  const digest = crypto.createHash('sha256');
  for (const p of paths) {
    digest.update(p);
    digest.update(await fs.readFile(path.join(root, p)));
  }
  digest.update(await fs.readFile(__filename));
  const revision = digest.digest('hex').slice(0, 16);

  const source =
    "// Generated by tools/build-sw.cjs. Public static assets only.\nconst VERSION = '0.8.0-__REVISION__';\nconst ROOT = new URL('./',self.location.href);\nconst PREFIX = 'finance-shell-'+encodeURIComponent(ROOT.pathname)+'-';\nconst CACHE = PREFIX+VERSION;\nconst FILES = __FILES__;\nconst ALLOWED = new Set(FILES.map(file=>new URL(file,ROOT).href));\nALLOWED.add(new URL('web/',ROOT).href);\nfunction safe(request){\n const url=new URL(request.url);\n if(url.hash && !['#login','#home','#transactions','#import','#bank-import','#stocks','#cards','#invoices','#settings'].includes(url.hash))return false;\n url.hash='';\n return request.method==='GET' && url.origin===ROOT.origin && !url.search &&\n  !request.headers.has('authorization') && !request.headers.has('range') &&\n  ALLOWED.has(url.href);\n}\nself.addEventListener('install',event=>{\n event.waitUntil((async()=>{\n  const cache=await caches.open(CACHE);\n  try{\n   await cache.addAll(FILES.map(file=>new Request(new URL(file,ROOT),{credentials:'omit',cache:'reload'})));\n  }catch(error){await caches.delete(CACHE);throw error;}\n })());\n // No skipWaiting: never replace a running PDF/OAuth session automatically.\n});\nself.addEventListener('activate',event=>{\n event.waitUntil((async()=>{\n  for(const key of await caches.keys())if(key.startsWith(PREFIX)&&key!==CACHE)await caches.delete(key);\n  await self.clients.claim();\n })());\n});\nself.addEventListener('fetch',event=>{\n if(!safe(event.request))return; // User documents, APIs, OAuth and query requests bypass this worker.\n event.respondWith((async()=>{\n  const url=new URL(event.request.url);url.hash='';\n  const key=url.href===new URL('web/',ROOT).href?new URL('web/index.html',ROOT).href:url.href;\n  const cache=await caches.open(CACHE);\n  const hit=await cache.match(key);\n  if(hit)return hit;\n  // Never cache a runtime response, even when a public resource was evicted.\n  return fetch(event.request);\n })());\n});\n"
      .replace('__REVISION__', revision)
      .replace('__FILES__', JSON.stringify(paths, null, 2));

  await fs.writeFile(path.join(root, 'sw.js'), source);
  console.log(
    JSON.stringify({
      version: '0.8.0',
      revision,
      staticAssets: paths.length,
      cachePolicy: 'immutable-public-allowlist'
    })
  );
})().catch(e => {
  console.error(e);
  process.exit(1);
});
